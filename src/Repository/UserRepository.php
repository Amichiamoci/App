    public function findByRole(string $role): array
    {
        $qb = $this->createQueryBuilder(alias: 'u');

        $qb
            ->andWhere(where: $qb->expr()->like(x: 'u.roles', y: ':role'))
            ->setParameter(key: 'role', value: '%'.$role.'%');

        return $qb
            ->getQuery()
            ->getResult();
    }
